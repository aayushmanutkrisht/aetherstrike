import assert from 'node:assert/strict';
import {normalizeName,validName,saveName,readName,readScores,addScore,topPlayers,sortTopScores,clearScores,scoresToCSV,SCORE_LIMIT,SCORES_KEY} from '../src/leaderboard/Leaderboard.ts';
const data=new Map();
const store={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value),removeItem:key=>data.delete(key)};
assert.equal(normalizeName('   Ashish   Sinha  '),'Ashish Sinha');
assert.equal(validName(' '),false);
assert.equal(validName('AS'),true);
assert.equal(saveName(' Ashish Sinha ',store),true);
assert.equal(readName(store),'Ashish Sinha');
assert.deepEqual(readScores(store),[]);
const run=(player,score,accuracy,result='defeat')=>({player,score,accuracy,hits:20,shots:50,sectors:3,totalSectors:6,result});
assert.equal(addScore(run('Ashish Sinha',1000,50),store).saved,true);
addScore(run('Player Two',1800,68,'victory'),store);
addScore(run('Ashish Sinha',2300,70,'victory'),store);
assert.equal(readScores(store).length,3);
assert.deepEqual(topPlayers(readScores(store)).map(e=>[e.player,e.score]),[['Ashish Sinha',2300],['Player Two',1800]]);
assert.equal(sortTopScores(readScores(store))[0].score,2300);
assert.ok(scoresToCSV(readScores(store)).includes('Ashish Sinha'));
assert.throws(()=>addScore(run('Z',100,20),store),/at least 2/);
data.set(SCORES_KEY,'garbage'); assert.deepEqual(readScores(store),[]); data.delete(SCORES_KEY);
for(let i=0;i<SCORE_LIMIT+7;i++)addScore(run('Player '+i,i*100,100),store);
assert.equal(readScores(store).length,SCORE_LIMIT);
assert.equal(clearScores(store),true);assert.deepEqual(readScores(store),[]);
console.log('Leaderboard unit tests passed');
